// Generates supabase/seed/sample_products.sql from src/lib/bookstore/sample-products.json,
// so the app's offline sample catalog and the database seed never drift apart.
// Usage: node scripts/generate-sample-seed.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const products = JSON.parse(readFileSync("src/lib/bookstore/sample-products.json", "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
const num = (v) => (v === null || v === undefined ? "null" : String(v));

const cols = [
  "slug", "title", "title_en", "description", "description_en", "category", "collection", "level",
  "price", "prices", "compare_at_prices", "format", "bundle_items",
  "is_available", "is_coming_soon", "is_featured", "sort_order", "is_sample",
];

const rows = products.map((p) =>
  `  (${[
    q(p.slug), q(p.title), q(p.title_en), q(p.description), q(p.description_en), q(p.category), q(p.collection), q(p.level),
    num(p.price), `${q(JSON.stringify(p.prices))}::jsonb`, `${q(JSON.stringify(p.compare_at_prices))}::jsonb`, arr(p.format), arr(p.bundle_items),
    p.is_available, p.is_coming_soon, p.is_featured, num(p.sort_order), true,
  ].join(", ")})`,
);

const sql = `-- GENERATED by scripts/generate-sample-seed.mjs — do not edit by hand.
-- Sample catalog for testing the Bookstore. Remove with: delete from public.products where is_sample;
insert into public.products (${cols.join(", ")}) values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;

mkdirSync("supabase/seed", { recursive: true });
writeFileSync("supabase/seed/sample_products.sql", sql);
console.log(`Wrote ${products.length} sample products to supabase/seed/sample_products.sql`);
